#!/usr/bin/env python3
"""Add a release signing config to Tauri's generated Android Gradle project.

The Android project is generated by `tauri android init` and is gitignored, so
CI patches it after generation. The keystore path, alias and passwords come
from environment variables so no signing material is stored in the repo.
"""

from pathlib import Path

GRADLE = Path("src-tauri/gen/android/app/build.gradle.kts")

SIGNING_CONFIG = """    signingConfigs {
        create("release") {
            storeFile = file(System.getenv("ANDROID_KEYSTORE_PATH")!!)
            storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")
            keyAlias = System.getenv("ANDROID_KEY_ALIAS")
            keyPassword = System.getenv("ANDROID_KEY_PASSWORD")
            storeType = "PKCS12"
        }
    }

"""


def main() -> None:
    source = GRADLE.read_text()
    if "signingConfigs" in source:
        raise SystemExit("Android signing config already present")

    if "    buildTypes {\n" not in source:
        raise SystemExit("unexpected build.gradle.kts: buildTypes block not found")
    source = source.replace(
        "    buildTypes {\n", SIGNING_CONFIG + "    buildTypes {\n", 1
    )

    release = '        getByName("release") {\n'
    if release not in source:
        raise SystemExit("unexpected build.gradle.kts: release build type not found")
    source = source.replace(
        release,
        release + '            signingConfig = signingConfigs.getByName("release")\n',
        1,
    )

    GRADLE.write_text(source)
    print(f"patched {GRADLE}")


if __name__ == "__main__":
    main()
